-- Gemeentelijst voor stadsaanvragen (Nederland en België)
--
-- Spelers kiezen een gemeente uit een lijst ("Gent, Oost-Vlaanderen") in plaats van vrije tekst. Zo is een aanvraag
-- altijd een bestaande gemeente en kan de beheerder hem met een tik goedkeuren: de Edge Function osm-import zoekt
-- de gemeente op met de code uit deze lijst (ref:gemeentecode in Nederland, ref:INS in België).
--
-- Code: GM plus de CBS-gemeentecode (Nederland) of BE plus de NIS-code (België).
-- Bronnen: PDOK-locatieserver (342 Nederlandse gemeenten, 2026) en Wikidata (565 Belgische gemeenten, na de
-- Vlaamse fusies van 2025). Waalse gemeenten staan onder hun officiële Franse naam; ook_bekend_als is de andere
-- taal of een gangbare naam (Den Bosch, Luik, Bruxelles) en dient alleen om te zoeken.

create table public.gemeenten (
  code text primary key check (code ~ '^(GM[0-9]{4}|BE[0-9]{5})$'),
  naam text not null,
  provincie text not null,
  land text not null check (land in ('NL', 'BE')),
  ook_bekend_als text
);
create unique index gemeenten_naam_idx on public.gemeenten (lower(naam));
comment on table public.gemeenten is 'Gemeenten die een speler kan aanvragen. Iedereen leest; alleen migraties schrijven.';

alter table public.gemeenten enable row level security;
revoke all on public.gemeenten from anon, authenticated;
grant select on public.gemeenten to anon, authenticated;
create policy "iedereen leest gemeenten" on public.gemeenten for select to anon, authenticated using (true);

