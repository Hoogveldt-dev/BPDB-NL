create or replace function private.vraag_stad_aan(p_code text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  ik uuid := auth.uid();
  g public.gemeenten;
  nieuw bigint;
begin
  if ik is null then
    raise exception 'Log eerst in' using errcode = '28000';
  end if;
  select * into g from public.gemeenten where code = upper(trim(coalesce(p_code, '')));
  if not found then
    raise exception 'Kies een gemeente uit de lijst' using errcode = 'P0001';
  end if;
