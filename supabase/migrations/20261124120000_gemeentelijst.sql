  end if;
  if exists (select 1 from public.stadsaanvragen s where s.door_id = ik and s.gemeente_code = g.code) then
    raise exception 'Je hebt % al aangevraagd', g.naam using errcode = 'P0001';
  end if;
  if (select count(*) from public.stadsaanvragen s where s.door_id = ik and s.op > now() - interval '1 day') >= 5 then
    raise exception 'Je hebt vandaag al 5 steden aangevraagd. Probeer het morgen weer.' using errcode = 'P0001';
  end if;
  insert into public.stadsaanvragen (door_id, stad, gemeente_code) values (ik, g.naam, g.code) returning id into nieuw;
  return nieuw;
end;
$$;

